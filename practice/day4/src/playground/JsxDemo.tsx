function JsxDemo() {
  const scores = [88, 92, 70];

  return (
    <div>
      <h1>점수판</h1>
      <ul>
        {/*
          🐍 Python이면: [f"{i+1}번: {s}점" for i, s in enumerate(scores)]
             리스트 컴프리헨션과 같은 역할 — 배열을 순회해서 "다른 모양의 배열"(여기선 JSX 배열)로 바꾼다.
          JS 자체 설명: .map(콜백)은 원본 배열(scores)을 건드리지 않고,
             콜백이 반환한 값들을 모아 "새 배열"을 만들어 돌려주는 배열 메서드.
             여기서는 콜백이 <li> JSX를 반환하므로 결과는 <li> 배열이 되고,
             React는 배열 안의 JSX 요소들을 순서대로 화면에 그려준다.
        */}
        {scores.map((s, i) => (
          // (s, i) → s: 현재 순회 중인 값(예: 88), i: 인덱스(0부터 시작).
          // 🐍 enumerate(scores)의 (i, s)와 순서만 반대라고 생각하면 됨.
          <li key={i}>
            {/*
              ⚠️ key={i}: React가 리스트 항목을 구분하는 이름표.
              형제 요소들 중 어떤 게 그대로고 어떤 게 바뀌었는지 diff할 때 사용.
              지금은 배열 순서가 안 바뀌니 index를 써도 되지만,
              실무에서 항목이 추가/삭제/재정렬되는 리스트라면 고유 id를 써야 버그가 안 생김.
            */}
            {i + 1}번: {s}점 {s >= 90 && "🎉"}
            {/*
              {i + 1}, {s} → JSX 중괄호 {} 안에는 "값을 만드는 JS 표현식"을 그대로 쓸 수 있음.
                🐍 f"{i+1}번: {s}점"의 f-string과 비슷한 역할.
              {s >= 90 && "🎉"} → 조건부 렌더링 패턴.
                JS에서 && 는 왼쪽이 falsy면 왼쪽 값을, truthy면 오른쪽 값을 반환.
                즉 s >= 90 이 false면 결과는 false(화면엔 아무것도 안 그려짐),
                true면 결과는 "🎉" 문자열(화면에 그려짐).
                🐍 삼항 없이 "조건 and 값"만 쓰는 것과 같은 느낌 — else 쪽이 필요 없을 때 씀.
            */}
          </li>
        ))}
      </ul>
    </div>
  );
}

export default JsxDemo;